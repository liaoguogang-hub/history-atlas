def canon(role):
    if not role:
        return "历史人物"
    parts = [p.strip() for p in re.split(r"[、,，/]", role) if p.strip()]
    out = []
    for p in parts:
        c = ROLE_CANON.get(p, p)
        if c not in out:
            out.append(c)
    return "、".join(out) if out else "历史人物"


def main():
    for sc in ["china", "world"]:
        p = f"data/{sc}.json"
        d = json.load(io.open(p, encoding="utf-8"))
        n = 0
        roles = collections.Counter()
        for f in d.get("figures") or []:
            old = f.get("role") or ""
            new = canon(old)
            if new != old:
                f["role"] = new
                n += 1
            roles[new] += 1
        io.open(p, "w", encoding="utf-8").write(
            json.dumps(d, ensure_ascii=False, indent=1))
        print(f"{sc}: normalized {n} roles; distinct roles = {len(roles)}")
        for k, v in roles.most_common(30):
            print(f"    {v:5d}  {k}")


if __name__ == "__main__":
    main()
