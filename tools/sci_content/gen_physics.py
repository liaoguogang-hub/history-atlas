def period(pid, name, alias, parent, sy, ey, sdt, edt, color, summary,
           territory, capital, population, culture, key_figures, rel_events, tags):
    return {
        "id": P + pid,
        "name": name,
        "alias": alias,
        "parentId": (P + parent) if parent else None,
        "startYear": sy,
        "endYear": ey,
        "startDateText": sdt,
        "endDateText": edt,
        "colorKey": color,
        "summary": summary,
        "territory": territory,
        "capital": capital,
        "population": population,
        "culture": culture,
        "keyFigures": [F + f for f in key_figures],
        "relatedEvents": [E + e for e in rel_events],
        "tags": tags,
    }


def event(pid, name, year, year_end, date_text, period_id, category, location,
          summary, detail, importance, figures, tags):
    return {
        "id": E + pid,
        "name": name,
        "year": year,
        "yearEnd": year_end,
        "dateText": date_text,
        "periodId": P + period_id,
        "category": category,
        "location": location,
        "summary": summary,
        "detail": detail,
        "importance": importance,
        "figures": [F + f for f in figures],
        "tags": tags,
    }


def figure(pid, name, alias, birth, death, life_text, role, period_id, gender,
           summary, biography, achievements, quotes, rel_events, rel_figures, tags):
    return {
        "id": F + pid,
        "name": name,
        "alias": alias,
        "birthYear": birth,
        "deathYear": death,
        "lifeText": life_text,
        "role": role,
        "periodId": P + period_id,
        "gender": gender,
        "summary": summary,
        "biography": biography,
        "achievements": achievements,
        "quotes": quotes,
        "relatedEvents": [E + e for e in rel_events],
        "relatedFigures": [F + f for f in rel_figures],
        "tags": tags,
    }


