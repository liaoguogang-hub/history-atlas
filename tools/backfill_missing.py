def main():
    path = sys.argv[1]
    data = json.load(io.open(path, encoding="utf-8"))
    event_ids = {e["id"] for e in data["events"]}
    figure_ids = {f["id"] for f in data["figures"]}

    # ---- 补事件 ----
    new_events = []
    for eid, (name, year, summary, cat, imp) in EV.items():
        if eid in event_ids:
            continue
        pid = None
        best = None
        for key, (p, s, e) in CUR.items():
            if eid.startswith("ev-" + key):
                pid = p
                best = (s, e)
                break
        if pid is None:
            # 从缺失 id 猜：取前缀最长匹配
            parts = eid[3:].split("-")
            for i in range(len(parts), 0, -1):
                key = "-".join(parts[:i])
                if key in CUR:
                    pid = CUR[key][0]
                    break
        if pid is None:
            print(f"  !! 无法推断时期: {eid}")
            continue
        sign = "公元前" if year < 0 else "公元"
        ay = abs(year)
        dt = f"{sign}{ay}年" if ay < 10000 else f"{sign}{ay}年"
        new_events.append({
            "id": eid,
            "periodId": pid,
            "name": name,
            "year": year,
            "dateText": dt,
            "summary": summary,
            "category": cat,
            "importance": imp,
        })
        event_ids.add(eid)

    # ---- 补人物 ----
    new_figures = []
    for fid, (name, pid, summary, role, by, dy) in MISSING_FIG.items():
        if fid in figure_ids:
            continue
        def fmt(y):
            if y is None:
                return None
            if isinstance(y, str):
                return None
            return ("公元前%d年" % abs(y)) if y < 0 else ("公元%d年" % y)
        lt = "生卒不详"
        if by is not None and dy is not None:
            lt = f"{fmt(by)}－{fmt(dy)}"
        elif dy is not None:
            lt = f"？－{fmt(dy)}"
        new_figures.append({
            "id": fid,
            "name": name,
            "periodId": pid,
            "role": role,
            "birthYear": by if isinstance(by, int) else None,
            "deathYear": dy if isinstance(dy, int) else None,
            "lifeText": lt,
            "summary": summary,
            "bio": summary + " 相关事迹详见史籍记载，其一生与所处时代的政治格局、社会变动与思想文化演进紧密相系。",
            "gender": "unknown",
            "tags": [name, pid],
        })
        figure_ids.add(fid)

    if new_events:
        data["events"].extend(new_events)
    if new_figures:
        data["figures"].extend(new_figures)

    io.open(path, "w", encoding="utf-8").write(
        json.dumps(data, ensure_ascii=False, indent=1))
    print(f"{path}: +{len(new_events)} events, +{len(new_figures)} figures")


if __name__ == "__main__":
    main()
