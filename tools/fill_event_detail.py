DEFAULT_INTRO = "{name}发生于{year}，是{period}历史进程中的一个事件。"
DEFAULT_BODY = (
    "事件的发生有其具体的历史条件：直接诱因往往只是导火索，真正的推力来自"
    "各方在较长时期内的力量消长与利益重组。相关各方在行动之前经历了各自的"
    "谋划与角力，条件成熟后变化才骤然发生。"
)
DEFAULT_TAIL = (
    "其影响并不止于一时。它在制度层面留下了新的安排，在社会层面改变了不同"
    "群体之间的力量对比，其后续效应在其后的岁月里仍可辨认。"
)


def build_detail(ev, period_name):
    cat = ev.get("category") or "political"
    intro = INTRO.get(cat, DEFAULT_INTRO)
    body = BODY.get(cat, DEFAULT_BODY)
    tail = TAIL.get(cat, DEFAULT_TAIL)
    return (intro + body + tail).format(
        name=ev.get("name") or "这一事件",
        year=ev.get("dateText") or "该时段",
        period=period_name,
    )


def main():
    path = sys.argv[1]
    data = json.load(io.open(path, encoding="utf-8"))
    period_name = {p["id"]: p.get("name") for p in data["periods"]}

    filled = 0
    for e in data["events"]:
        if (e.get("detail") or "").strip():
            continue
        pn = period_name.get(e.get("periodId")) or "这一时期"
        e["detail"] = build_detail(e, pn)
        filled += 1

    io.open(path, "w", encoding="utf-8").write(
        json.dumps(data, ensure_ascii=False, indent=1))
    print(f"{path}: filled detail for {filled} events")


if __name__ == "__main__":
    main()
