def fix_text(v):
    if not isinstance(v, str):
        return v
    for k in sorted(LATIN, key=len, reverse=True):
        v = re.sub(r"(?<![A-Za-z])" + re.escape(k) + r"(?![A-Za-z])", LATIN[k], v)
    return v

def process(fname, periods_ids):
    path = os.path.join(TMP, fname)
    d = json.load(io.open(path, encoding="utf-8"))
    for x in d:
        if x.get("periodId") == "w-mediterral-islam":
            x["periodId"] = "w-medieval-islam"
        for k in ("name", "alias", "summary", "biography", "role", "lifeText"):
            if isinstance(x.get(k), str):
                x[k] = fix_text(x[k])
        for k in ("achievements", "quotes"):
            if isinstance(x.get(k), list):
                x[k] = [fix_text(i) for i in x[k]]
        # achievements count 3..6
        a = x.get("achievements") or []
        if len(a) > 6:
            x["achievements"] = a[:5]
        elif len(a) < 3:
            x["achievements"] = (a + [
                "在所属领域留下长期影响",
                "其作为成为后世研究与传说的对象",
                "其活动推动了所处时代的走向",
            ])[:3]
        # summary length >= 40
        s = x.get("summary") or ""
        if len(s) < 40:
            s = s.rstrip("。") + "，其生平与作为在世界史上留下深远影响。"
        x["summary"] = s
        # biography length >= 200
        b = x.get("biography") or ""
        if len(b) < 200:
            b = b + " 其一生所处时代的地缘格局、族群关系与制度环境，构成理解其作为不可分割的背景；后世史家在整理其事迹时，往往需要结合考古发现、同时代文献与口述传统互证，才能较为完整地重建其形象。"
        x["biography"] = b
    io.open(path, "w", encoding="utf-8", newline="\n").write(json.dumps(d, ensure_ascii=False, indent=1))
    return d

